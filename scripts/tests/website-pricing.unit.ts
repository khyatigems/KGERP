import assert from "node:assert/strict";
import { calculatePrice, validatePriceFloor, productSchema, publicProduct } from "../../lib/website/contracts";
const product=productSchema.parse({inventoryId:"private-id",sku:"TEST",title:"Test gemstone",slug:"test-gemstone",category:"loose-gemstones",description:"Verified product details",images:["https://example.com/actual.jpg"],price:1000,cost:700,quantity:8,charges:[{name:"Gateway",basis:"sale-percent",value:2},{name:"Packaging",basis:"flat",value:20}],volumeTiers:[{quantity:3,unitPrice:900}]});
assert.deepEqual(calculatePrice(product),{unitPrice:1000,msp:740,earning:260,belowMsp:false});
assert.equal(calculatePrice(product,3,10).unitPrice,810);
assert.equal(calculatePrice(product,3,10).msp,736.2);
assert.throws(()=>validatePriceFloor(product,30),/below website MSP/);
assert.equal(calculatePrice(product,3,10,false).unitPrice,900);
assert.throws(()=>calculatePrice(product,0),/Invalid/);
assert.throws(()=>calculatePrice(product,1,100),/Invalid/);
assert.throws(()=>productSchema.parse({...product,images:["javascript:alert(1)"]}));
const publicValue=publicProduct("p",product);
assert.equal("cost" in publicValue,false);assert.equal("inventoryId" in publicValue,false);assert.equal("charges" in publicValue,false);
console.log("Website pricing: transaction-based fees, tier discounts, MSP floors and private field exclusion passed.");
