import assert from "node:assert/strict";
import { trustedErpSender, connectFromErp, connectionStatus, repairConnection } from "../../extensions/work-tracker/src/erp-connection.js";
import { defaults, sendEvents } from "../../extensions/work-tracker/src/api-client.js";
const sender = { url: "https://erp.khyatigems.com/work-tracker" };
const message = { erpUrl: "https://erp.khyatigems.com", token: `kgwt_${"x".repeat(43)}`, browserName: "Office PC", credentialId: "test" };
const verify = async () => new Response(JSON.stringify({ connected: true, credential: { id: "test", name: "Office PC", expiresAt: "2099-01-01" } }));
assert.equal(trustedErpSender({ url: "https://erp.khyatigems.com.evil.test" }), false);
assert.equal(trustedErpSender({ url: "https://evil.test" }), false);
assert.equal(trustedErpSender({ url: "http://localhost:3000/work-tracker" }), true);
await assert.rejects(connectFromErp(message, { url: "https://evil.test" }, defaults, [], verify), /Untrusted/);
await assert.rejects(connectFromErp({ ...message, erpUrl: "https://other.test" }, sender, defaults, [], verify), /mismatch/);
await assert.rejects(connectFromErp(message, sender, { ...defaults, token: message.token }, [], verify), /already/);
await assert.rejects(connectFromErp(message, sender, defaults, [{}], verify), /pending/);
await assert.rejects(connectFromErp(message, sender, defaults, [], async () => new Response("{}", { status: 401 })), /expired/);
const next = await connectFromErp(message, sender, defaults, [], verify);
assert.equal(next.enabled, false);
assert.equal(next.browserName, "Office PC");
const connected = { ...defaults, token: message.token, browserName: "Stale name" };
const status = await connectionStatus(sender, connected, { queue: [{}], lastSync: "2026-10-25" }, verify);
assert.equal(status.state, "connected");
assert.equal(status.browserName, "Office PC", "ERP name overrides stale local and legacy settings");
assert.equal(status.credentialId, "test", "legacy token-only connections recover their credential identity");
assert.equal(status.pendingCount, 1);
assert.equal((await connectionStatus(sender, { ...connected, erpUrl: "https://ERP.khyatigems.com:443/" }, {}, verify)).state, "connected", "equivalent origins are not another ERP");
await sendEvents({ ...connected, erpUrl: "https://ERP.khyatigems.com:443/" }, [], async url => {
 assert.equal(url, "https://erp.khyatigems.com/api/work-tracker/activity-events", "legacy formatting must not cause a redirect");
 return new Response(JSON.stringify({ accepted: [] }));
});
const localConnection = { ...connected, erpUrl: "http://localhost:3000", credentialId: "test", enabled: true };
const repaired = await repairConnection(localConnection, message.erpUrl, verify);
assert.equal(repaired.erpUrl, message.erpUrl);
assert.equal(repaired.token, localConnection.token, "address repair must keep the original access");
assert.equal(repaired.enabled, true, "address repair keeps the tracking preference");
await assert.rejects(repairConnection(localConnection, message.erpUrl, async () => new Response(JSON.stringify({ connected: true, credential: { id: "another-browser", name: "Other" } }))), /same browser access/);
await assert.rejects(repairConnection(localConnection, message.erpUrl, async () => new Response("{}", { status: 401 })), /expired or revoked/);
await assert.rejects(repairConnection({ ...localConnection, credentialId: undefined }, message.erpUrl, async url => {
 if (url.startsWith("http://localhost")) throw new Error("offline");
 return verify();
}), /Cannot reach/, "legacy access without a verified identity cannot migrate across servers blindly");
assert.equal(Object.hasOwn(status, "token"), false);
const invalid = async () => new Response("{}", { status: 401 });
assert.equal((await connectionStatus(sender, connected, {}, invalid)).state, "invalid");
assert.equal((await connectionStatus(sender, connected, {}, async () => { throw new Error("offline"); })).state, "unreachable");
assert.equal((await connectionStatus(sender, connected, {}, async () => new Response("{}", { status: 500 }))).state, "unreachable");
assert.equal((await connectionStatus(sender, connected, {}, async () => new Response(JSON.stringify({ connected: true })))).state, "update-required");
const other = await connectionStatus({ url: "http://localhost:3000/work-tracker" }, connected, { queue: [{}] }, () => assert.fail("must not contact the other ERP"));
assert.equal(other.state, "other-erp");
assert.equal(Object.hasOwn(other, "credentialId"), false);
assert.equal(Object.hasOwn(other, "browserName"), false);
assert.equal(Object.hasOwn(other, "pendingCount"), false);
let calls = 0;
const reconnected = await connectFromErp(message, sender, connected, [], async () => ++calls === 1 ? invalid() : verify());
assert.equal(reconnected.credentialId, "test", "revoked credentials can reconnect without a manual disconnect");
assert.equal(reconnected.enabled, false);
await assert.rejects(connectFromErp(message, sender, connected, [], async () => { throw new Error("offline"); }), /already/);
await assert.rejects(connectFromErp({ ...message, credentialId: "different" }, sender, defaults, [], verify), /verification/);
console.log("Work tracker pairing tests passed: trusted origins, queue isolation, credential verification and opt-in tracking");
