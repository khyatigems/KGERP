import assert from "node:assert/strict";
import { mkdtempSync, rmSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { hash } from "bcryptjs";
import { NextRequest } from "next/server";
import { isPublicPage } from "@/lib/public-routes";
import { codeHash, contextText, requestContext, sameOrigin } from "@/lib/security/core";

async function main() {
  const temp = mkdtempSync(path.join(tmpdir(), "kg-security-"));
  process.env.DATABASE_URL = `file:${path.join(temp, "test.db").replaceAll("\\", "/")}`;
  process.env.TURSO_DATABASE_URL = ""; process.env.TURSO_URL = "";
  process.env.AUTH_SECRET = "isolated-security-test-secret-not-for-production";
  process.env.AUTH_URL = "https://erp.test";
  process.env.VERCEL = "";
  const { prisma } = await import("@/lib/prisma");
  const { ZohoMailConnector } = await import("@/lib/email/connectors/zoho");
  const originalSend = ZohoMailConnector.prototype.send;
  const messages: Array<{ to: string; text: string; subject: string; html?: string }> = [];
  ZohoMailConnector.prototype.send = async function(message) {
    messages.push({ to: message.to, text: message.text || "", subject: message.subject, html: message.html });
    return { status: "SENT", providerMessageId: "isolated-test" };
  };
  try {
    const sql = execFileSync(process.execPath, [path.resolve("node_modules/prisma/build/index.js"), "migrate", "diff", "--from-empty", "--to-schema-datamodel", "prisma/schema.prisma", "--script"], { encoding: "utf8" });
    for (const statement of sql.split(";").map(x => x.replace(/--[^\n]*/g, "").trim()).filter(Boolean)) await prisma.$executeRawUnsafe(statement);
    const service = await import("@/lib/security/service");
    await service.ensureSecuritySchema();
    const password = "IsolatedTestPassword!42";
    const user = await prisma.user.create({ data: { name: "Security test", email: "admin@erp.test", password: await hash(password, 10), role: "SUPER_ADMIN" } });
    const request = new Request("https://erp.test/api/auth/otp", { method: "POST", headers: { origin: "https://erp.test", "user-agent": "Mozilla/5.0 (Windows NT 10.0) Chrome/130.0 Safari/537.36 Edg/130.1", "x-forwarded-for": "1.2.3.4" } });
    assert.equal(requestContext(request).ip, "Unavailable", "untrusted forwarded IP must be ignored off Vercel");
    assert.equal(requestContext(request).browser, "Edg/130.1");
    assert.match(contextText(request), /Windows/);
    assert.equal(sameOrigin(request), true);
    assert.equal(sameOrigin(new Request("https://erp.test", { headers: { origin: "https://evil.test" } })), false);
    for (const url of ["/login", "/invoice/secret", "/verify/serial", "/V/serial", "/preview/SKU"]) assert.equal(isPublicPage(url), true, url);
    for (const url of ["/invoices", "/invoices/id", "/invoices/id/payments/p/receipt", "/preview/label/serial", "/preview/label/serial/", "/invoice-internal", "/preview-internal/SKU"]) assert.equal(isPublicPage(url), false, url);
    const preview = readFileSync("app/preview/[slug]/page.tsx", "utf8");
    assert.doesNotMatch(preview, /prisma\.sale|invoiceSales|payableInvoice|payNowUrl|token:\s*true/);

    await Promise.all([service.ensureSecuritySchema(), service.ensureSecuritySchema()]);
    assert.deepEqual(await service.getSecurityPolicy(), { enabled: false, email: "", alerts: true, version: "disabled" });
    const rates = await Promise.all(Array.from({ length: 8 }, () => service.rateLimit("parallel-budget", 3, 60)));
    assert.equal(rates.filter(Boolean).length, 3, "parallel requests share one durable rate budget");
    const challenge = () => service.createChallenge(user.id, "login", { version: "v1" }, "security@erp.test", user.email, request);
    const lastCode = () => messages.at(-1)!.text.match(/Code: (\d{6})/)![1];
    let cookie = await challenge(); let code = lastCode();
    assert.match(messages.at(-1)!.html || "", /Your verification code/);
    assert.ok(messages.at(-1)!.html?.includes(`>${code}</div>`), "Zoho receives the branded HTML with a contiguous OTP");
    assert.match(messages.at(-1)!.text, /Browser \(reported\): Edg\/130.1/);
    assert.match(messages.at(-1)!.text, /Approximate location:/);
    assert.equal(await service.consumeChallenge(cookie.replace(/.$/, cookie.endsWith("0") ? "1" : "0"), user.id, "login", code), null, "browser binding required");
    assert.equal(await service.consumeChallenge(cookie, "other-user", "login", code), null, "user binding required");
    assert.equal(await service.consumeChallenge(cookie, user.id, "settings", code), null, "purpose binding required");
    assert.equal(await service.consumeChallenge(cookie, user.id, "login", code === "000000" ? "111111" : "000000"), null);
    assert.deepEqual(await service.consumeChallenge(cookie, user.id, "login", code), { version: "v1" });
    assert.equal(await service.consumeChallenge(cookie, user.id, "login", code), null, "OTP replay rejected");
    cookie = await challenge(); code = lastCode();
    for (let i = 0; i < 5; i++) assert.equal(await service.consumeChallenge(cookie, user.id, "login", code === "000000" ? "111111" : "000000"), null);
    assert.equal(await service.consumeChallenge(cookie, user.id, "login", code), null, "correct code rejected after guess budget exhausted");
    cookie = await challenge(); code = lastCode();
    await prisma.$executeRaw`UPDATE "SecurityChallenge" SET expiresAt = 1 WHERE id = ${cookie.split(".")[0]}`;
    assert.equal(await service.consumeChallenge(cookie, user.id, "login", code), null, "expired code rejected");
    const oldCookie = await challenge(), oldCode = lastCode();
    cookie = await challenge(); code = lastCode();
    assert.equal(await service.consumeChallenge(oldCookie, user.id, "login", oldCode), null, "resend invalidates previous code");
    const parallel = await Promise.all([service.consumeChallenge(cookie, user.id, "login", code), service.consumeChallenge(cookie, user.id, "login", code)]);
    assert.equal(parallel.filter(Boolean).length, 1, "parallel successful requests can consume only once");
    const settingsCookie = await service.createChallenge(user.id, "settings", { email: "new@erp.test" }, "new@erp.test", user.email, request, "old@erp.test");
    const primary = messages.at(-2)!.text.match(/Code: (\d{6})/)![1];
    const secondary = messages.at(-1)!.text.match(/code: (\d{6})/)![1];
    assert.equal(await service.consumeChallenge(settingsCookie, user.id, "settings", primary), null, "changing mailbox needs current mailbox proof too");
    assert.deepEqual(await service.consumeChallenge(settingsCookie, user.id, "settings", primary, secondary), { email: "new@erp.test" });
    ZohoMailConnector.prototype.send = async () => ({ status: "FAILED", error: "isolated simulated outage" });
    await assert.rejects(challenge(), /Zoho/);
    const pending = await prisma.$queryRaw<Array<{ consumed: number }>>`SELECT consumed FROM "SecurityChallenge" WHERE userId = ${user.id} AND purpose = 'login' AND consumed = 0`;
    assert.equal(pending.length, 0, "failed delivery cannot leave usable challenge");
    ZohoMailConnector.prototype.send = async function(message) { messages.push({ to: message.to, text: message.text || "", subject: message.subject, html: message.html }); return { status: "SENT" }; };

    const { handlers } = await import("@/lib/auth");
    const csrf = await handlers.GET(new NextRequest("https://erp.test/api/auth/csrf"));
    const csrfToken = (await csrf.json()).csrfToken;
    const csrfCookie = csrf.headers.getSetCookie().map(v => v.split(";")[0]).join("; ");
    async function signIn(otp = "", challengeCookie = "", recoveryCode = "") {
      return handlers.POST(new NextRequest("https://erp.test/api/auth/callback/credentials", {
        method: "POST", headers: { "Content-Type": "application/x-www-form-urlencoded", cookie: `${csrfCookie}; erp-login-challenge=${challengeCookie}`, origin: "https://erp.test" },
        body: new URLSearchParams({ csrfToken, email: user.email, password, otp, recoveryCode }),
      }));
    }
    const sessionCookie = (response: Response) => response.headers.getSetCookie().find(v => /(?:__Secure-)?next-auth\.session-token=/.test(v))?.split(";")[0];
    assert.ok(sessionCookie(await signIn()), "password-only login works while policy is disabled");
    const recovery = await service.saveSecurityPolicy({ enabled: true, email: "security@erp.test", alerts: true, version: "v1" }, user.id, "disabled");
    assert.equal(recovery.length, 8);
    assert.equal(sessionCookie(await signIn()), undefined, "direct credentials callback cannot bypass mandatory OTP");
    const { POST: startLogin } = await import("@/app/api/auth/otp/route");
    assert.equal((await startLogin(new Request("https://erp.test/api/auth/otp", { method: "POST", headers: { origin: "https://evil.test" }, body: "{}" }))).status, 403);
    const mailCount = messages.length;
    assert.equal((await startLogin(new Request("https://erp.test/api/auth/otp", { method: "POST", headers: { origin: "https://erp.test" }, body: JSON.stringify({ email: user.email, password: "wrong" }) }))).status, 401);
    assert.equal(messages.length, mailCount, "wrong password cannot trigger OTP email");
    const start = await startLogin(new Request("https://erp.test/api/auth/otp", { method: "POST", headers: { origin: "https://erp.test" }, body: JSON.stringify({ email: user.email, password }) }));
    assert.equal(start.status, 200);
    const startedCookie = start.headers.getSetCookie().find(v => v.startsWith("erp-login-challenge="))!.split(";")[0].slice("erp-login-challenge=".length);
    code = lastCode();
    assert.equal((await start.clone().json()).required, true);
    const signed = await signIn(code, startedCookie);
    const signedCookie = sessionCookie(signed);
    assert.ok(signedCookie, "correct password and browser-bound OTP issue a session");
    assert.equal(sessionCookie(await signIn(code, startedCookie)), undefined, "credentials callback rejects OTP replay");
    assert.ok(sessionCookie(await signIn("", "", recovery[0])), "recovery works without email delivery/challenge");
    assert.equal(sessionCookie(await signIn("", "", recovery[0])), undefined, "recovery code is single-use");
    await service.saveSecurityPolicy({ enabled: true, email: "security@erp.test", alerts: true, version: "v2" }, user.id, "v1");
    const oldSession = await handlers.GET(new NextRequest("https://erp.test/api/auth/session", { headers: { cookie: signedCookie! } }));
    assert.equal(await oldSession.json(), null, "older policy session revoked");
    assert.equal(await service.consumeRecoveryCode(user.id, "v1", recovery[1]), false, "older recovery codes revoked");
    for (let i = 0; i < 3; i++) assert.equal(sessionCookie(await signIn()), undefined);
    assert.equal(messages.filter(message => message.subject.includes("Repeated verification failures")).length, 1, "repeated OTP failures send one throttled alert");
    await assert.rejects(service.saveSecurityPolicy({ enabled: true, email: "a@erp.test", alerts: true, version: "v3" }, user.id, "v1"), /changed/);
    const { handleSecuritySettings } = await import("@/lib/security/settings-http");
    const settingsRequest = (body: Record<string, unknown>, cookieValue = "") => new Request("https://erp.test/api/settings/security", { method: "POST", headers: { origin: "https://erp.test", cookie: `erp-security-challenge=${cookieValue}` }, body: JSON.stringify({ email: "next@erp.test", enabled: true, alerts: true, password, ...body }) });
    const identify = async () => ({ user: { id: user.id } });
    assert.equal((await handleSecuritySettings(settingsRequest({ action: "request-code" }), async () => null)).status, 401);
    assert.equal((await handleSecuritySettings(settingsRequest({ action: "request-code" }), identify, async () => false)).status, 403);
    assert.equal((await handleSecuritySettings(settingsRequest({ action: "request-code", password: "wrong" }), identify, async () => true)).status, 401);
    const sendSettings = await handleSecuritySettings(settingsRequest({ action: "request-code" }), identify, async () => true);
    assert.equal(sendSettings.status, 200);
    const setCookie = sendSettings.headers.getSetCookie()[0];
    assert.match(setCookie, /HttpOnly/i); assert.match(setCookie, /SameSite=strict/i);
    assert.equal((await sendSettings.json()).needsCurrentCode, true);
    const setupCookie = setCookie.split(";")[0].slice("erp-security-challenge=".length);
    const setupCode = messages.at(-2)!.text.match(/Code: (\d{6})/)![1];
    const setupCurrent = messages.at(-1)!.text.match(/code: (\d{6})/)![1];
    assert.equal((await handleSecuritySettings(settingsRequest({ action: "save", code: setupCode }, setupCookie), identify, async () => true)).status, 400);
    const saved = await handleSecuritySettings(settingsRequest({ action: "save", code: setupCode, currentCode: setupCurrent }, setupCookie), identify, async () => true);
    assert.equal(saved.status, 200);
    const savedCodes = (await saved.json()).recoveryCodes as string[];
    assert.equal(savedCodes.length, 8);
    assert.equal((await service.getSecurityPolicy()).email, "next@erp.test");
    assert.equal((await handleSecuritySettings(settingsRequest({ action: "save", code: setupCode, currentCode: setupCurrent }, setupCookie), identify, async () => true)).status, 400, "settings verification is single-use");
    const activePolicy = await service.getSecurityPolicy();
    assert.equal(await service.countRecoveryCodes(user.id, activePolicy.version), 8);
    const other = await prisma.user.create({ data: { name: "Other administrator", email: "other@erp.test", password: await hash(password, 10), role: "SUPER_ADMIN" } });
    await service.replaceRecoveryCodes(other.id, activePolicy.version);
    await assert.rejects(service.replaceRecoveryCodes(user.id, "obsolete-policy"), /changed/);
    const { handleRecoveryCodes } = await import("@/lib/security/recovery-http");
    const recoveryRequest = (body: Record<string, unknown>, cookieValue = "") => new Request("https://erp.test/api/settings/security/recovery", { method: "POST", headers: { origin: "https://erp.test", cookie: `erp-recovery-challenge=${cookieValue}` }, body: JSON.stringify({ password, ...body }) });
    assert.equal((await handleRecoveryCodes(recoveryRequest({ action: "request-code" }), async () => null)).status, 401);
    assert.equal((await handleRecoveryCodes(recoveryRequest({ action: "request-code" }), identify, async () => false)).status, 403);
    assert.equal((await handleRecoveryCodes(new Request("https://erp.test/api/settings/security/recovery", { method: "POST", headers: { origin: "https://evil.test" }, body: "{}" }), identify, async () => true)).status, 403);
    assert.equal((await handleRecoveryCodes(recoveryRequest({ action: "request-code", password: "wrong" }), identify, async () => true)).status, 401);
    const recoveryStart = await handleRecoveryCodes(recoveryRequest({ action: "request-code" }), identify, async () => true);
    assert.equal(recoveryStart.status, 200);
    assert.match(messages.at(-1)!.html || "", /Protect your recovery access/);
    const recoveryOtp = lastCode();
    const recoveryCookie = recoveryStart.headers.getSetCookie()[0].split(";")[0].slice("erp-recovery-challenge=".length);
    assert.equal((await handleRecoveryCodes(recoveryRequest({ action: "generate", code: recoveryOtp }), identify, async () => true)).status, 400, "recovery generation requires its browser cookie");
    assert.equal((await handleRecoveryCodes(recoveryRequest({ action: "generate", code: recoveryOtp === "000000" ? "111111" : "000000" }, recoveryCookie), identify, async () => true)).status, 400);
    const generated = await handleRecoveryCodes(recoveryRequest({ action: "generate", code: recoveryOtp }, recoveryCookie), identify, async () => true);
    assert.equal(generated.status, 200);
    assert.match(generated.headers.get("cache-control") || "", /no-store/);
    const replacementCodes = (await generated.json()).recoveryCodes as string[];
    assert.equal(replacementCodes.length, 8);
    assert.equal(await service.countRecoveryCodes(other.id, activePolicy.version), 8, "replacement preserves another administrator's codes");
    assert.deepEqual(await service.getSecurityPolicy(), activePolicy, "recovery replacement preserves the global session policy");
    assert.equal(await service.consumeRecoveryCode(user.id, activePolicy.version, savedCodes[0]), false, "earlier recovery set is invalidated");
    assert.equal(await service.consumeRecoveryCode(user.id, activePolicy.version, replacementCodes[0]), true);
    assert.equal(await service.countRecoveryCodes(user.id, activePolicy.version), 7);
    assert.equal((await handleRecoveryCodes(recoveryRequest({ action: "generate", code: recoveryOtp }, recoveryCookie), identify, async () => true)).status, 400, "recovery verification cannot be replayed");
    await prisma.setting.update({ where: { key: service.POLICY_KEY }, data: { value: JSON.stringify({ ...activePolicy, enabled: false }) } });
    const beforeDisabled = messages.length;
    assert.equal((await handleRecoveryCodes(recoveryRequest({ action: "request-code" }), identify, async () => true)).status, 409, "recovery generation requires enabled 2FA on the server");
    assert.equal(messages.length, beforeDisabled);
    await prisma.setting.update({ where: { key: service.POLICY_KEY }, data: { value: "corrupt" } });
    await assert.rejects(service.getSecurityPolicy(), "corrupt policy must fail closed");
    assert.notEqual(codeHash("challenge1", "123456"), codeHash("challenge2", "123456"));
    console.log("Security regression tests passed: public routes, invoice isolation, durable rate limits, OTP binding/expiry/attempts/replay/concurrency/resend/outage, mailbox change, direct Auth.js bypass, recovery and session revocation.");
  } finally {
    ZohoMailConnector.prototype.send = originalSend;
    await prisma.$disconnect();
    // Only the exact temporary fixture directory created above is removed.
    assert.ok(path.resolve(temp).startsWith(path.resolve(tmpdir()) + path.sep));
    rmSync(temp, { recursive: true, force: true });
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
