import fs from "node:fs";
import path from "node:path";
import ts from "typescript";

// Inventory concrete modal instances, not just filenames. Run after adding a modal.
const entries = [];
const bypasses = [];
function files(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((item) => {
    const filename = path.join(directory, item.name);
    return item.isDirectory() ? files(filename) : /\.tsx?$/.test(filename) ? [filename] : [];
  });
}
for (const filename of [...files("app"), ...files("components")]) {
  const file = filename.replaceAll("\\", "/");
  const source = fs.readFileSync(filename, "utf8");
  const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const location = (node) => `${file}:${ast.getLineAndCharacterOfPosition(node.getStart(ast)).line + 1}`;
  const compact = (value) => value.replace(/\s+/g, " ").trim().replaceAll("|", "\\|").slice(0, 150);
  function visit(node) {
    if (ts.isJsxElement(node) || ts.isJsxSelfClosingElement(node)) {
      const opening = ts.isJsxElement(node) ? node.openingElement : node;
      const tag = opening.tagName.getText(ast);
      const attr = (name) => opening.attributes.properties.find((property) => ts.isJsxAttribute(property) && property.name.getText(ast) === name);
      const role = attr("role")?.initializer?.getText(ast);
      if (["DialogContent", "AlertDialogContent", "SheetContent"].includes(tag)) {
        const titles = [];
        const findTitle = (child) => {
          if (ts.isJsxElement(child) && /^(DialogTitle|AlertDialogTitle|SheetTitle)$/.test(child.openingElement.tagName.getText(ast))) titles.push(compact(child.children.map((part) => part.getText(ast)).join(" ")));
          else ts.forEachChild(child, findTitle);
        };
        ts.forEachChild(node, findTitle);
        entries.push({ location: location(node), kind: tag, title: titles.join(" / ") || "Custom content / preview", route: `Shared ${tag === "SheetContent" ? "sheet" : tag === "AlertDialogContent" ? "alert" : "dialog"}` });
      }
      if (tag === "dialog" || role === '"dialog"' || role === '"alertdialog"') {
        if (file === "components/notifications/notification-bell.tsx") entries.push({ location: location(node), kind: "Panel", title: "Notifications inbox", route: "Styled anchored panel; retains inbox keyboard handling" });
        else bypasses.push(`${location(node)}: raw modal markup`);
      }
      if (/Primitive\.Content$/.test(tag) && /@radix-ui\/react-(?:alert-)?dialog/.test(source) && !["components/ui/dialog.tsx", "components/ui/alert-dialog.tsx", "components/ui/sheet.tsx"].includes(file)) bypasses.push(`${location(node)}: direct modal primitive`);
      if (tag === "div" && /fixed\s+inset-0/.test(attr("className")?.initializer?.getText(ast) || "") && /(?:modal|dialog)/i.test(file)) bypasses.push(`${location(node)}: custom fixed overlay`);
    }
    if (ts.isCallExpression(node)) {
      const callee = node.expression.getText(ast);
      if (["window.confirm", "window.alert", "window.prompt", "globalThis.confirm", "globalThis.alert"].includes(callee)) bypasses.push(`${location(node)}: native browser modal`);
      if (callee === "confirm" && source.includes("useErpConfirmation")) {
        const argument = node.arguments[0];
        const title = argument && ts.isObjectLiteralExpression(argument) ? argument.properties.find((property) => ts.isPropertyAssignment(property) && property.name.getText(ast) === "title") : undefined;
        entries.push({ location: location(node), kind: "Confirmation", title: compact(title?.initializer?.getText(ast) || "Confirmation request"), route: "Shared confirmation provider" });
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(ast);
}
entries.sort((a, b) => a.location.localeCompare(b.location));
if (bypasses.length) {
  console.error("Modal audit found bypasses:\n" + bypasses.join("\n"));
  process.exit(1);
}
const counts = Object.entries(entries.reduce((result, entry) => ({ ...result, [entry.kind]: (result[entry.kind] || 0) + 1 }), {})).map(([kind, count]) => `${count} ${kind}`).join(", ");
const report = `# ERP modal migration checklist

Generated by \`node scripts/audit-modals.mjs\`. Re-run when modal locations change.

## Coverage

${entries.length} source instances: ${counts}. Source inventory includes ERP routes, shared tools, and customer-facing inventory previews. Counts describe declarations and confirmation call sites, not every runtime record or conditional branch.

- [x] Shared Dialog: branded identity, rounded surface, blurred backdrop, responsive scrolling, consistent header/footer and close control.
- [x] Shared AlertDialog: same identity and surface; confirmation, warning, and destructive tones.
- [x] Shared Sheet: matching backdrop, identity, surface, and action styling while preserving side-panel layouts.
- [x] Sales: all three sale-deletion steps use destructive styling; sale creation uses confirmation/warning styling; WhatsApp inherits the shared dialog.
- [x] Dashboard matched pairs: replaced bespoke fixed overlay with shared accessible Dialog.
- [x] Notification inbox: matching anchored-panel surface; keeps inbox behavior.
- [x] Customer-facing previews retain their specialized media/payment layouts inside the shared dialog; payment card uses the new corner radius.
- [x] Audit finds no native browser prompts, raw modal markup, custom modal overlays, or direct primitive bypasses outside the shared components.
- [ ] Runtime walkthrough of every listed workflow with representative data, on desktop and mobile, in light and dark themes. Source migration does not imply every workflow was opened interactively.

## Per-modal implementation checklist

Checked means connected to the migrated shared UI (or explicitly reviewed anchored panel). It does not claim a completed interactive test.

| Migrated | Source location | Modal / workflow | UI path |
| --- | --- | --- | --- |
${entries.map((entry) => `| [x] | \`${entry.location}\` | ${entry.title} | ${entry.route} |`).join("\n")}
`;
const destination = "docs/modal-migration-checklist.md";
if (process.argv.includes("--check")) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, "utf8") !== report) {
    console.error("Modal checklist is stale. Run node scripts/audit-modals.mjs.");
    process.exit(1);
  }
} else {
  fs.mkdirSync("docs", { recursive: true });
  fs.writeFileSync(destination, report);
}
console.log(`Modal audit passed: ${entries.length} instances; no bypasses. Checklist: ${destination}`);
