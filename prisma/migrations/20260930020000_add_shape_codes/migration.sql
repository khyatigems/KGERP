-- Shape codes: master list of gem shapes used by inventory forms
CREATE TABLE IF NOT EXISTS "ShapeCode" (
  "id" TEXT NOT NULL PRIMARY KEY,
  "name" TEXT NOT NULL,
  "code" TEXT NOT NULL,
  "status" TEXT NOT NULL DEFAULT 'ACTIVE',
  "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS "ShapeCode_name_key" ON "ShapeCode"("name");
CREATE UNIQUE INDEX IF NOT EXISTS "ShapeCode_code_key" ON "ShapeCode"("code");

